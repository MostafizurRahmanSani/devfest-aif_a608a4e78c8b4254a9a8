let LANG = "en";
try { LANG = localStorage.getItem("se-lang") === "bn" ? "bn" : "en"; } catch (e) {}

function t(key, p) {
  let s = (DICT[LANG] && DICT[LANG][key]) || DICT.en[key] || key;
  if (p) for (const k in p) s = s.split("{" + k + "}").join(fmtNum(p[k]));
  return s;
}

// Numbers shown in Bangla digits in Bangla mode
function fmtNum(v) {
  if (typeof v !== "number") return String(v);
  return new Intl.NumberFormat(LANG === "bn" ? "bn-BD" : "en-US").format(v);
}

function setLang(l) {
  LANG = l;
  try { localStorage.setItem("se-lang", l); } catch (e) {}
  document.documentElement.lang = l;
}
